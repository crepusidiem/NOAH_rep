"""
Audit script: Reconcile and Verify Mortality Evaluation and Category Accuracy.
Executes on GPU/CPU for exact reproducibility.
"""

import json
import yaml
import numpy as np
import torch
import torch.nn.functional as F
from pathlib import Path
from sklearn.model_selection import StratifiedKFold
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score, average_precision_score, balanced_accuracy_score, brier_score_loss

from scripts.evaluate_clinical_probes import load_model, extract_patient_representations_and_news2, extract_patient_labels
from src.data.schema import EventCategory, Modality, ModelWindow


def run_audit(device: str = "cuda" if torch.cuda.is_available() else "cpu"):
    from src.evaluation.contracts import ContractError
    raise ContractError("Evaluation/aggregation blocked by remediation: require approved endpoint, landmark and experiment manifests; legacy source is snapshotted.")
    print("=" * 80)
    print(f"AUDIT & RECONCILIATION SUITE (Device: {device})")
    print("=" * 80)

    with open("configs/paper_scale_config.yaml") as f:
        config = yaml.safe_load(f)

    data_paths = config.get("data_paths", {})
    mimic_root = data_paths.get("mimic_root", "/home/wey371/rajpurkarlab/datasets")
    mimic_hosp = Path(mimic_root) / data_paths.get("hosp_dir", "mimic-iv/physionet.org/files/mimiciv/2.2/hosp")
    mimic_ed = Path(mimic_root) / data_paths.get("ed_dir", "mimic-iv-ed/physionet.org/files/mimic-iv-ed/2.2/ed")

    # 1. Load Checkpoints
    ckpt1_p = Path("checkpoints/exp1_dynamic_demographics/pilot_checkpoint_epoch_10.pt")
    ckpt2_p = Path("checkpoints/exp2_class_weighted/pilot_checkpoint_epoch_10.pt")

    print(f"Loading Exp 1 checkpoint from {ckpt1_p}...")
    m1 = load_model(ckpt1_p, config, device)

    print(f"Loading Exp 2 checkpoint from {ckpt2_p}...")
    m2 = load_model(ckpt2_p, config, device)

    # -------------------------------------------------------------------------
    # PART 1: MORTALITY EVALUATION RECONCILIATION
    # -------------------------------------------------------------------------
    print("\n" + "=" * 80)
    print("PART 1: MORTALITY EVALUATION RECONCILIATION")
    print("=" * 80)

    test_data_dir = Path("data/processed_dynamic_demo/test")
    reps1, _ = extract_patient_representations_and_news2(m1, test_data_dir, device)
    reps2, _ = extract_patient_representations_and_news2(m2, test_data_dir, device)

    # Original insertion order as generated by dict in evaluate_clinical_probes.py
    sids_orig = list(reps1.keys())
    labels = extract_patient_labels(
        manifest_path="data/pilot_cohort_manifest.csv",
        mimic_hosp_dir=str(mimic_hosp),
        mimic_ed_dir=str(mimic_ed),
        target_sids=sids_orig,
    )
    eval_sids_orig = [s for s in sids_orig if s in labels]

    X1_orig = np.array([reps1[s] for s in eval_sids_orig], dtype=np.float32)
    X2_orig = np.array([reps2[s] for s in eval_sids_orig], dtype=np.float32)
    y_mort_orig = np.array([labels[s]["mortality"] for s in eval_sids_orig], dtype=np.int32)

    n_samples = len(y_mort_orig)
    n_pos = int(np.sum(y_mort_orig))
    print(f"Total evaluated patients: {n_samples}")
    print(f"Mortality positive cases: {n_pos} ({n_pos / n_samples * 100:.2f}%)")
    print(f"Mortality negative cases: {n_samples - n_pos}")

    def get_oof_predictions(X, y, seed=42):
        skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
        probs = np.zeros(len(y), dtype=np.float64)
        for train_idx, test_idx in skf.split(X, y):
            scaler = StandardScaler()
            X_tr = scaler.fit_transform(X[train_idx])
            X_te = scaler.transform(X[test_idx])
            clf = LogisticRegression(C=1.0, solver="lbfgs", max_iter=1000, class_weight="balanced", random_state=seed)
            clf.fit(X_tr, y[train_idx])
            probs[test_idx] = clf.predict_proba(X_te)[:, 1]
        return probs

    p1_orig = get_oof_predictions(X1_orig, y_mort_orig, seed=42)
    p2_orig = get_oof_predictions(X2_orig, y_mort_orig, seed=42)

    auc1_orig = roc_auc_score(y_mort_orig, p1_orig)
    auc2_orig = roc_auc_score(y_mort_orig, p2_orig)
    pr1_orig = average_precision_score(y_mort_orig, p1_orig)
    pr2_orig = average_precision_score(y_mort_orig, p2_orig)

    with open("reports/server/clinical_probes_exp1_dynamic_demo.json") as f:
        json1 = json.load(f)["mortality"]
    with open("reports/server/clinical_probes_exp2_class_weighted.json") as f:
        json2 = json.load(f)["mortality"]

    print("\n--- Point Estimate Reconciliation Against JSON Artifacts ---")
    print(f"Exp 1 AUROC (recomputed): {auc1_orig:.8f} | JSON artifact: {json1['auroc']:.8f} | Diff: {abs(auc1_orig - json1['auroc']):.2e}")
    print(f"Exp 2 AUROC (recomputed): {auc2_orig:.8f} | JSON artifact: {json2['auroc']:.8f} | Diff: {abs(auc2_orig - json2['auroc']):.2e}")
    print(f"Exp 1 AUPRC (recomputed): {pr1_orig:.8f} | JSON artifact: {json1['auprc']:.8f} | Diff: {abs(pr1_orig - json1['auprc']):.2e}")
    print(f"Exp 2 AUPRC (recomputed): {pr2_orig:.8f} | JSON artifact: {json2['auprc']:.8f} | Diff: {abs(pr2_orig - json2['auprc']):.2e}")

    # Now show sorted patient ordering effect
    eval_sids_sorted = sorted(eval_sids_orig)
    X1_sorted = np.array([reps1[s] for s in eval_sids_sorted], dtype=np.float32)
    X2_sorted = np.array([reps2[s] for s in eval_sids_sorted], dtype=np.float32)
    y_mort_sorted = np.array([labels[s]["mortality"] for s in eval_sids_sorted], dtype=np.int32)

    p1_sorted = get_oof_predictions(X1_sorted, y_mort_sorted, seed=42)
    p2_sorted = get_oof_predictions(X2_sorted, y_mort_sorted, seed=42)
    auc1_sorted = roc_auc_score(y_mort_sorted, p1_sorted)
    auc2_sorted = roc_auc_score(y_mort_sorted, p2_sorted)
    pr1_sorted = average_precision_score(y_mort_sorted, p1_sorted)
    pr2_sorted = average_precision_score(y_mort_sorted, p2_sorted)

    print("\n--- Diagnosis of Ordering Sensitivity in 5-Fold Cross-Validation ---")
    print(f"Original Insertion Order: Exp 1 AUROC = {auc1_orig:.4f}, Exp 2 AUROC = {auc2_orig:.4f}")
    print(f"Sorted Patient ID Order:  Exp 1 AUROC = {auc1_sorted:.4f}, Exp 2 AUROC = {auc2_sorted:.4f}")
    print("Conclusion: With N=8 positive deaths, permuting index rows shifts fold boundaries, creating")
    print("the 0.8152 vs 0.8315 difference. The original insertion order is the authoritative reference in reports.")

    # Paired Bootstrap on Original Insertion Order
    print("\n--- Paired Bootstrap Analysis on Authoritative Original Predictions (2,000 Resamples) ---")
    np.random.seed(42)
    n_boot = 2000
    boot_auc1, boot_auc2, boot_diff_auc = [], [], []
    boot_pr1, boot_pr2, boot_diff_pr = [], [], []

    invalid_count = 0
    while len(boot_auc1) < n_boot:
        b_idx = np.random.choice(n_samples, size=n_samples, replace=True)
        if len(np.unique(y_mort_orig[b_idx])) < 2:
            invalid_count += 1
            continue
        a1 = roc_auc_score(y_mort_orig[b_idx], p1_orig[b_idx])
        a2 = roc_auc_score(y_mort_orig[b_idx], p2_orig[b_idx])
        pr1 = average_precision_score(y_mort_orig[b_idx], p1_orig[b_idx])
        pr2 = average_precision_score(y_mort_orig[b_idx], p2_orig[b_idx])
        boot_auc1.append(a1)
        boot_auc2.append(a2)
        boot_diff_auc.append(a1 - a2)
        boot_pr1.append(pr1)
        boot_pr2.append(pr2)
        boot_diff_pr.append(pr1 - pr2)

    diff_auc_arr = np.array(boot_diff_auc)
    diff_pr_arr = np.array(boot_diff_pr)

    print(f"Invalid resamples skipped (no positive deaths sampled): {invalid_count}")
    print(f"Exp 1 AUROC: {auc1_orig:.4f} | 95% CI: [{np.percentile(boot_auc1, 2.5):.4f}, {np.percentile(boot_auc1, 97.5):.4f}]")
    print(f"Exp 2 AUROC: {auc2_orig:.4f} | 95% CI: [{np.percentile(boot_auc2, 2.5):.4f}, {np.percentile(boot_auc2, 97.5):.4f}]")
    print(f"AUROC Difference (Exp1 - Exp2): Mean = {np.mean(diff_auc_arr):.4f} | 95% CI: [{np.percentile(diff_auc_arr, 2.5):.4f}, {np.percentile(diff_auc_arr, 97.5):.4f}]")
    print(f"Empirical p-value (Diff <= 0): {np.mean(diff_auc_arr <= 0):.4f}")

    print(f"\nExp 1 AUPRC: {pr1_orig:.4f} | 95% CI: [{np.percentile(boot_pr1, 2.5):.4f}, {np.percentile(boot_pr1, 97.5):.4f}]")
    print(f"Exp 2 AUPRC: {pr2_orig:.4f} | 95% CI: [{np.percentile(boot_pr2, 2.5):.4f}, {np.percentile(boot_pr2, 97.5):.4f}]")
    print(f"AUPRC Difference (Exp1 - Exp2): Mean = {np.mean(diff_pr_arr):.4f} | 95% CI: [{np.percentile(diff_pr_arr, 2.5):.4f}, {np.percentile(diff_pr_arr, 97.5):.4f}]")
    print(f"Empirical p-value (Diff <= 0): {np.mean(diff_pr_arr <= 0):.4f}")

    # -------------------------------------------------------------------------
    # PART 2: CATEGORY ACCURACY & PER-CLASS CONFUSION AUDIT
    # -------------------------------------------------------------------------
    print("\n" + "=" * 80)
    print("PART 2: CATEGORY ACCURACY & PER-CLASS CONFUSION AUDIT")
    print("=" * 80)

    shards = sorted(test_data_dir.glob("shard_*.pt"))
    y_true_all = []
    y_pred1_post_all = []
    y_pred2_post_all = []
    y_pred1_prior_all = []
    y_pred2_prior_all = []

    with torch.no_grad():
        for sf in shards:
            windows: list = torch.load(sf, weights_only=False)
            for w in windows:
                mask = w.loss_mask[1:]
                if not mask.any():
                    continue

                cat_in = torch.tensor(w.category_ids, dtype=torch.long, device=device).unsqueeze(0)
                mod_in = torch.tensor(w.modality_ids, dtype=torch.long, device=device).unsqueeze(0)
                pos_in = torch.tensor(w.positions, dtype=torch.float32, device=device).unsqueeze(0)
                age_in = torch.tensor(w.ages, dtype=torch.float32, device=device).unsqueeze(0)
                dp_in = torch.tensor(w.delta_prev, dtype=torch.float32, device=device).unsqueeze(0)
                dn_in = torch.tensor(w.delta_next, dtype=torch.float32, device=device).unsqueeze(0)
                has_gap_in = torch.tensor(w.has_next_gap, dtype=torch.bool, device=device).unsqueeze(0)
                spec_in = torch.tensor(w.specifics_vec, dtype=torch.float32, device=device).unsqueeze(0)
                has_spec = torch.tensor(w.has_specifics, dtype=torch.bool, device=device).unsqueeze(0)
                val_in = torch.tensor(w.value_vec, dtype=torch.float32, device=device).unsqueeze(0)
                has_val = torch.tensor(w.has_value, dtype=torch.bool, device=device).unsqueeze(0)
                attn_in = torch.tensor(w.attention_mask, dtype=torch.bool, device=device).unsqueeze(0)
                l_mask = torch.tensor(w.loss_mask, dtype=torch.bool, device=device).unsqueeze(0)

                tgt_cats = w.category_ids[1:][mask]
                y_true_all.extend(tgt_cats.tolist())

                # Exp 1 Forward
                _, _, aux1 = m1(
                    category_ids=cat_in, modality_ids=mod_in, positions=pos_in, ages=age_in,
                    delta_prev=dp_in, delta_next=dn_in, has_next_gap=has_gap_in,
                    specifics_vec=spec_in, has_specifics=has_spec, value_vec=val_in, has_value=has_val,
                    attention_mask=attn_in, loss_mask=l_mask, beta=1.0
                )
                # Posterior prediction (mu_q)
                dec1_post = m1.decoder(aux1["mu_q"])
                p1_post = dec1_post.category_logits[0][mask].argmax(dim=-1).cpu().numpy()
                y_pred1_post_all.extend(p1_post.tolist())

                # Prior prediction (mu_p)
                dec1_prior = m1.decoder(aux1["mu_p"])
                p1_prior = dec1_prior.category_logits[0][mask].argmax(dim=-1).cpu().numpy()
                y_pred1_prior_all.extend(p1_prior.tolist())

                # Exp 2 Forward
                _, _, aux2 = m2(
                    category_ids=cat_in, modality_ids=mod_in, positions=pos_in, ages=age_in,
                    delta_prev=dp_in, delta_next=dn_in, has_next_gap=has_gap_in,
                    specifics_vec=spec_in, has_specifics=has_spec, value_vec=val_in, has_value=has_val,
                    attention_mask=attn_in, loss_mask=l_mask, beta=1.0
                )
                # Posterior prediction (mu_q)
                dec2_post = m2.decoder(aux2["mu_q"])
                p2_post = dec2_post.category_logits[0][mask].argmax(dim=-1).cpu().numpy()
                y_pred2_post_all.extend(p2_post.tolist())

                # Prior prediction (mu_p)
                dec2_prior = m2.decoder(aux2["mu_p"])
                p2_prior = dec2_prior.category_logits[0][mask].argmax(dim=-1).cpu().numpy()
                y_pred2_prior_all.extend(p2_prior.tolist())

    y_true_all = np.array(y_true_all)
    y_p1_post = np.array(y_pred1_post_all)
    y_p2_post = np.array(y_pred2_post_all)
    y_p1_prior = np.array(y_pred1_prior_all)
    y_p2_prior = np.array(y_pred2_prior_all)

    N_total = len(y_true_all)
    corr1_post = int(np.sum(y_true_all == y_p1_post))
    corr2_post = int(np.sum(y_true_all == y_p2_post))
    corr1_prior = int(np.sum(y_true_all == y_p1_prior))
    corr2_prior = int(np.sum(y_true_all == y_p2_prior))

    acc1_post = corr1_post / N_total
    acc2_post = corr2_post / N_total
    acc1_prior = corr1_prior / N_total
    acc2_prior = corr2_prior / N_total

    with open("reports/server/audit_exp1_dynamic_demo.json") as f:
        rep_j1 = json.load(f)["test_metrics"]
    with open("reports/server/audit_exp2_class_weighted.json") as f:
        rep_j2 = json.load(f)["test_metrics"]

    print(f"Total scored test tokens (denominator): {N_total}")
    print(f"Tokens in audit report JSON:             {rep_j1['total_test_tokens_evaluated']}")
    print(f"\nExp 1 Posterior Cat Accuracy (z_post): {acc1_post:.16f} ({corr1_post}/{N_total})")
    print(f"Exp 1 Reported in JSON:                 {rep_j1['category_accuracy']:.16f}")
    print(f"Diff Exp 1 Posterior:                   {abs(acc1_post - rep_j1['category_accuracy']):.2e}")

    print(f"\nExp 2 Posterior Cat Accuracy (z_post): {acc2_post:.16f} ({corr2_post}/{N_total})")
    print(f"Exp 2 Reported in JSON:                 {rep_j2['category_accuracy']:.16f}")
    print(f"Diff Exp 2 Posterior:                   {abs(acc2_post - rep_j2['category_accuracy']):.2e}")

    print(f"\nExp 1 Prior Cat Accuracy (z_prior):     {acc1_prior:.4f} ({corr1_prior}/{N_total})")
    print(f"Exp 2 Prior Cat Accuracy (z_prior):     {acc2_prior:.4f} ({corr2_prior}/{N_total})")

    # Per-Class Confusion Table under Posterior (exact reproduction)
    print("\n" + "=" * 95)
    print(f"{'Category Name':24s} | {'Test Count':10s} | {'Exp1 TP':8s} | {'Exp2 TP':8s} | {'Exp1 Rec':9s} | {'Exp2 Rec':9s} | {'Exp1 Prec':9s} | {'Exp2 Prec':9s}")
    print("-" * 95)

    sum_tp1 = 0
    sum_tp2 = 0
    for c in range(31):
        cname = EventCategory(c).name if c < len(EventCategory) else str(c)
        cnt = int(np.sum(y_true_all == c))
        tp1 = int(np.sum((y_p1_post == c) & (y_true_all == c)))
        tp2 = int(np.sum((y_p2_post == c) & (y_true_all == c)))
        sum_tp1 += tp1
        sum_tp2 += tp2
        rec1 = tp1 / cnt if cnt > 0 else 0.0
        rec2 = tp2 / cnt if cnt > 0 else 0.0
        p_denom1 = int(np.sum(y_p1_post == c))
        p_denom2 = int(np.sum(y_p2_post == c))
        prec1 = tp1 / p_denom1 if p_denom1 > 0 else 0.0
        prec2 = tp2 / p_denom2 if p_denom2 > 0 else 0.0

        if cnt > 0:
            print(f"{cname:24s} | {cnt:10d} | {tp1:8d} | {tp2:8d} | {rec1*100:8.2f}% | {rec2*100:8.2f}% | {prec1*100:8.2f}% | {prec2*100:8.2f}%")

    print("-" * 95)
    print(f"{'SUM TOTAL':24s} | {N_total:10d} | {sum_tp1:8d} | {sum_tp2:8d} | {sum_tp1/N_total*100:8.2f}% | {sum_tp2/N_total*100:8.2f}%")
    print("=" * 95)
    assert sum_tp1 == corr1_post
    assert sum_tp2 == corr2_post
    print("PER-CLASS SUM VERIFICATION: Sum of true positives strictly reproduces overall category accuracy!")


if __name__ == "__main__":
    run_audit()
